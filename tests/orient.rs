//! The arrival report at the CLI boundary: measured lists with units and
//! tails, honest ties and placeholders, and follow-up commands that run.
mod support;
use serde_json::Value;
use std::process::{Command, Output};
use support::Fixture;

const WORKSPACE: &str = "[workspace]\nmembers = ['app', 'base']\nresolver = '3'\n";
const APP_MANIFEST: &str = "[package]\nname = 'app'\nversion = '0.1.0'\nedition = '2024'\n[dependencies]\nbase = { path = '../base' }\n";
const CORE_MANIFEST: &str = "[package]\nname = 'base'\nversion = '0.1.0'\nedition = '2024'\n";

/// Two packages: `app` has a library and one binary, `base` a library, an
/// `@generated` module, and a file no module declaration reaches.
fn workspace() -> Fixture {
    Fixture::new(&[
        ("Cargo.toml", WORKSPACE),
        ("app/Cargo.toml", APP_MANIFEST),
        (
            "app/src/lib.rs",
            "pub fn run(token: base::Token) -> base::Token { base::helper(); token }\n",
        ),
        (
            "app/src/main.rs",
            "fn main() {\n    let _ = app::run(base::Token);\n}\n",
        ),
        ("base/Cargo.toml", CORE_MANIFEST),
        (
            "base/src/lib.rs",
            "pub mod generated;\npub mod parse;\n\npub struct Token;\npub struct Span;\n\npub fn helper() {}\n\npub fn first(token: Token) -> Token {\n    helper();\n    token\n}\n\npub fn second(token: Token) -> Token {\n    helper();\n    token\n}\n\npub fn third(span: Span) -> Token {\n    helper();\n    let _ = span;\n    Token\n}\n",
        ),
        (
            "base/src/parse.rs",
            "use crate::Token;\n\npub fn parse(token: Token) -> Token {\n    crate::helper();\n    let a = 1;\n    let b = 2;\n    let _ = a + b;\n    token\n}\n",
        ),
        (
            "base/src/generated.rs",
            "// This file is @generated by a tool; do not edit.\npub fn generated_one() {}\npub fn generated_two() {}\npub fn generated_three() {}\n",
        ),
        ("base/src/orphan.rs", "pub fn unreachable() {}\n"),
    ])
}

fn run_in(dir: &std::path::Path, args: &[&str]) -> Output {
    Command::new(env!("CARGO_BIN_EXE_cargo-atlas"))
        .args(args)
        .current_dir(dir)
        .output()
        .expect("run cargo-atlas")
}
fn report(fixture: &Fixture, args: &[&str]) -> Value {
    let mut all = vec!["orient", "--json"];
    all.extend(args);
    let output = run_in(fixture.path(), &all);
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    serde_json::from_slice(&output.stdout).expect("orient JSON")
}
fn section<'a>(report: &'a Value, id: &str) -> &'a Value {
    report["sections"]
        .as_array()
        .expect("sections")
        .iter()
        .find(|s| s["id"] == id)
        .unwrap_or_else(|| panic!("section {id}"))
}
fn strings(value: &Value) -> Vec<String> {
    value
        .as_array()
        .expect("array")
        .iter()
        .map(|v| v.as_str().expect("string").to_owned())
        .collect()
}

#[test]
fn sections_state_units_and_count_what_they_measure() {
    let fixture = workspace();
    let report = report(&fixture, &[]);
    assert_eq!(report["schema"], 1);
    assert_eq!(report["scope"], "workspace");
    let ids: Vec<_> = report["sections"]
        .as_array()
        .unwrap()
        .iter()
        .map(|s| s["id"].as_str().unwrap())
        .collect();
    assert_eq!(ids, ["mass", "blocks", "called", "mentioned"]);
    for section in report["sections"].as_array().unwrap() {
        for key in ["title", "unit", "order", "total_unit"] {
            assert!(
                !section[key].as_str().unwrap().is_empty(),
                "{key} in {section}"
            );
        }
        assert!(!section["all"].as_array().unwrap().is_empty());
    }
    let packages: Vec<_> = report["packages"]
        .as_array()
        .unwrap()
        .iter()
        .map(|p| p["name"].as_str().unwrap())
        .collect();
    assert_eq!(packages, ["app", "base"]);

    let called = &section(&report, "called")["rows"][0];
    assert_eq!(called["name"], "helper");
    assert_eq!(
        called["count"], 5,
        "five distinct functions call helper: {called}"
    );
    assert_eq!(called["path"], "base/src/lib.rs");
    let mentioned = &section(&report, "mentioned")["rows"][0];
    assert_eq!(mentioned["name"], "Token");
    assert_eq!(section(&report, "mentioned")["tied"], 1);

    assert!(strings(&report["generated_files"]).contains(&"base/src/generated.rs".to_owned()));
    assert_eq!(strings(&report["unmounted_files"]), ["base/src/orphan.rs"]);
    let base = section(&report, "mass")["rows"]
        .as_array()
        .unwrap()
        .iter()
        .find(|r| r["path"] == "base/src/")
        .expect("base directory row")
        .clone();
    assert!(base["generated_lines"].as_u64().unwrap() > 0, "{base}");
    let blocks = section(&report, "blocks")["rows"].as_array().unwrap();
    assert!(blocks.iter().all(|r| r["path"] != "base/src/generated.rs"));

    let resolution = &report["resolution"];
    assert!(resolution["calls_resolved"].as_u64().unwrap() >= 6);
    assert!(resolution["calls_unknown"].is_u64());
}

#[test]
fn every_list_reports_what_it_left_out_and_the_text_stays_one_page() {
    let fixture = workspace();
    // JSON is never cut: the text's row budget, or --all, changes nothing.
    let full = report(&fixture, &[]);
    for args in [&["--rows", "1"][..], &["--rows", "0"], &["--all"]] {
        assert_eq!(
            report(&fixture, args)["sections"],
            full["sections"],
            "{args:?}"
        );
    }
    for section in full["sections"].as_array().unwrap() {
        assert_eq!(section["more"], 0, "{section}");
    }
    assert!(
        full["sections"]
            .as_array()
            .unwrap()
            .iter()
            .any(|section| section["rows"].as_array().unwrap().len() > 1),
        "the fixture has a section with several rows"
    );
    let output = run_in(fixture.path(), &["orient", "--rows", "1"]);
    let text = String::from_utf8(output.stdout).unwrap();
    assert!(text.contains("more; cargo atlas concentration"), "{text}");
    // No share over a population mostly of calls into other packages.
    let calls = text
        .lines()
        .find(|l| l.starts_with("  calls: "))
        .expect("calls line");
    assert!(
        calls.contains("resolved to a workspace function;"),
        "{calls}"
    );
    assert!(!calls.contains('%'), "{calls}");
    assert!(
        text.contains("an index tells them apart: cargo atlas orient --semantic"),
        "{text}"
    );
    assert!(text.contains("not absent"));
    assert!(text.contains("counts are not use"));
    let full = run_in(fixture.path(), &["orient"]);
    assert!(full.stdout.len() < 8 * 1024, "{} bytes", full.stdout.len());
}

#[test]
fn printed_commands_run_as_printed() {
    let fixture = workspace();
    let report = report(&fixture, &[]);
    let next = report["next"].as_array().unwrap();
    assert!(
        next.iter().any(|n| strings(&n["args"])
            == [
                "flow",
                "--path",
                "app/src/main.rs",
                "--function",
                "main",
                "--depth",
                "1"
            ]),
        "the one binary's main is a concrete flow command: {next:?}"
    );
    let mut commands: Vec<Vec<String>> = next
        .iter()
        .filter(|n| n["runnable"] == true)
        .map(|n| strings(&n["args"]))
        .collect();
    commands.extend(
        report["sections"]
            .as_array()
            .unwrap()
            .iter()
            .map(|s| strings(&s["all"])),
    );
    for args in commands {
        let args: Vec<&str> = args.iter().map(String::as_str).collect();
        let output = run_in(fixture.path(), &args);
        assert!(
            output.status.success(),
            "{args:?}: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
}

#[test]
fn printed_commands_carry_the_root_the_caller_gave() {
    let fixture = workspace();
    let parent = fixture.path().parent().expect("fixture parent");
    let name = fixture.path().file_name().unwrap().to_str().unwrap();
    let output = run_in(parent, &["orient", "--root", name]);
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let text = String::from_utf8(output.stdout).unwrap();
    let line = text
        .lines()
        .find(|l| l.trim_start().starts_with("cargo atlas module "))
        .expect("module follow-up");
    assert!(line.contains(&format!("--root {name}")), "{line}");
}

#[test]
fn ties_and_several_binaries_get_placeholders_never_a_pick() {
    let fixture = Fixture::new(&[
        (
            "Cargo.toml",
            "[package]\nname='fixture'\nversion='0.1.0'\nedition='2024'\n[workspace]\n[[bin]]\nname='one'\npath='src/bin/one.rs'\n[[bin]]\nname='two'\npath='src/bin/two.rs'\n",
        ),
        (
            "src/lib.rs",
            "pub struct Left;\npub struct Right;\npub fn a(l: Left, r: Right) {}\npub fn b(l: Left, r: Right) {}\n",
        ),
        ("src/bin/one.rs", "fn main() {}\n"),
        ("src/bin/two.rs", "fn main() {}\n"),
    ]);
    let report = report(&fixture, &[]);
    let mentioned = section(&report, "mentioned");
    assert_eq!(mentioned["tied"], 2, "{mentioned}");
    let next = report["next"].as_array().unwrap();
    let name = next
        .iter()
        .find(|n| n["args"][0] == "name")
        .expect("name follow-up");
    assert_eq!(name["runnable"], false);
    assert!(name["args"][1].as_str().unwrap().starts_with('<'));
    let flow = next
        .iter()
        .find(|n| n["args"][0] == "flow")
        .expect("flow follow-up");
    assert_eq!(flow["runnable"], false);
    assert_eq!(flow["args"][2], "<bin root>");
    let text = String::from_utf8(run_in(fixture.path(), &["orient"]).stdout).unwrap();
    assert!(text.contains("the first 2 rows tie"), "{text}");
}

#[test]
fn a_package_scope_counts_that_package_and_follow_ups_use_its_directory() {
    let fixture = workspace();
    let report = report(&fixture, &["--scope", "base"]);
    assert_eq!(report["scope"], "base");
    assert_eq!(report["packages"].as_array().unwrap().len(), 1);
    assert_eq!(
        strings(&section(&report, "mass")["all"]),
        ["nontest-loc", "--in", "base"]
    );
    for row in section(&report, "mass")["rows"].as_array().unwrap() {
        assert!(row["path"].as_str().unwrap().starts_with("base/"), "{row}");
    }
    let missing = run_in(fixture.path(), &["orient", "--scope", "nowhere"]);
    assert!(!missing.status.success());
}
